/** Rows of booleans (true = ink) for one character. Throws for characters the font lacks. */
export function glyphFor(char: string): boolean[][] {
  const rows = GLYPHS[char.toUpperCase()];
  if (!rows) throw new Error(`Bitmap font has no glyph for character "${char}" (code ${char.charCodeAt(0)})`);
  return rows.map((row) => [...row].map((cell) => cell === '#'));
}

/** A grayscale canvas (0 = black, 255 = white) that can stamp text. */
export class GrayCanvas {
  readonly pixels: Uint8Array;

  constructor(
    readonly width: number,
    readonly height: number,
  ) {
    this.pixels = new Uint8Array(width * height).fill(255);
  }

  /** Draw text with its top-left corner at (x, y); each font pixel becomes scale x scale pixels. */
  drawText(text: string, x: number, y: number, scale: number): void {
    let cursorX = x;
    for (const char of text) {
      const glyph = glyphFor(char);
      for (let row = 0; row < GLYPH_HEIGHT; row++) {
        for (let col = 0; col < GLYPH_WIDTH; col++) {
          if (glyph[row]?.[col]) this.fillRect(cursorX + col * scale, y + row * scale, scale, scale);
        }
      }
      cursorX += (GLYPH_WIDTH + 1) * scale;
    }
  }

  private fillRect(x: number, y: number, w: number, h: number): void {
    for (let py = y; py < y + h; py++) {
      if (py < 0 || py >= this.height) throw new Error(`Text drawn outside the image at y=${py}`);
      for (let px = x; px < x + w; px++) {
        if (px < 0 || px >= this.width) throw new Error(`Text drawn outside the image at x=${px}`);
        this.pixels[py * this.width + px] = 0;
      }
    }
  }
}
