// npm run results:summary [-- --report reports/eval-<date>-live.json]
// Prints the 10-line results summary generated FROM the final live evaluation JSON and writes it to
// docs/RESULTS_SUMMARY.md. Never edit that file by hand: rerun this script.

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { type LiveReportJson, shortSummaryLines, summaryLines } from './eval/summaryLines.js';

function latestLiveReport(): string | null {
  if (!existsSync('reports')) return null;
  const files = readdirSync('reports').filter((f) => /^eval-\d{4}-\d{2}-\d{2}-live\.json$/.test(f)).sort();
  const last = files[files.length - 1];
  return last ? path.join('reports', last) : null;
}

const flag = process.argv.indexOf('--report');
const reportPath = flag >= 0 ? process.argv[flag + 1] : latestLiveReport();
if (!reportPath || !existsSync(reportPath)) {
  console.log('No live evaluation JSON found (reports/eval-<date>-live.json). Run the live evaluation first. Nothing written.');
  process.exit(1);
}
const json = JSON.parse(readFileSync(reportPath, 'utf8')) as LiveReportJson;
const lines = summaryLines(json);
const doc = [
  '# Results summary (generated)',
  '',
  `Generated by \`scripts/resultsSummary.ts\` from \`${reportPath.split(path.sep).join('/')}\`. Do not edit by hand.`,
  '',
  'All data is synthetic. The fixtures were written by the project author from templates, so these numbers',
  'measure this synthetic set only, not real-world policy documents.',
  '',
  ...lines,
  '',
].join('\n');
writeFileSync(path.join('docs', 'RESULTS_SUMMARY.md'), doc, 'utf8');
console.log(lines.join('\n'));
console.log(`\nWritten to docs/RESULTS_SUMMARY.md (from ${reportPath}).`);

// Generated lines go between markers in these files (never typed by hand): "results" gets the 10 lines,
// "results-short" the compact 5 (the case study has a word limit).
const short = shortSummaryLines(json);
const TARGETS: Array<[file: string, marker: string, block: string[]]> = [
  ['README.md', 'results', lines],
  [path.join('docs', 'CASE_STUDY.md'), 'results-short', short],
  [path.join('docs', 'private', 'NOTE_TO_AGENCY.md'), 'results', lines],
];
for (const [file, marker, block] of TARGETS) {
  if (!existsSync(file)) continue;
  const start = `<!-- ${marker}:start -->`;
  const end = `<!-- ${marker}:end -->`;
  const text = readFileSync(file, 'utf8');
  const from = text.indexOf(start);
  const to = text.indexOf(end);
  if (from >= 0 && to > from) {
    writeFileSync(file, `${text.slice(0, from + start.length)}\n${block.join('\n')}\n${text.slice(to)}`, 'utf8');
    console.log(`${file}: ${marker} section updated between its markers.`);
  } else {
    console.log(`${file}: no ${marker} markers; not changed.`);
  }
}
