// Markdown rendering of the evaluation report. Every number shown here is also in the JSON.

import type { FailureRow, Headline, PlumbingSummary, VersionSummary } from './aggregate.js';
import { COST_FORMULA, type Pricing } from './pricing.js';
import { formatRatio, type Ratio } from './score.js';

export interface ReportHeader {
  date: string;
  mode: 'fake' | 'live';
  model: string;
  promptVersion: string;
  compareRulesVersion: string;
  thresholds: { premiumMediumPct: number; premiumHighPct: number; windowMinDays: number; windowMaxDays: number };
  repeats: number;
  documents: number;
  generatedBy: string;
}

export const SYNTHETIC_LINE = 'All data is synthetic.';
export const AUTHOR_CAVEAT =
  'The fixtures (15 scenarios, 30 documents) were written by the project author from templates. These numbers measure THIS synthetic set only, not real-world policy documents, which are messier, longer and laid out in many different ways.';

const r = (x: Ratio) => formatRatio(x);
const pct = (x: number) => `${(x * 100).toFixed(2)}%`;

function table(head: string[], rows: string[][]): string[] {
  return [`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...rows.map((row) => `| ${row.join(' | ')} |`)];
}

function headerLines(h: ReportHeader): string[] {
  return [
    `- Date: ${h.date}`,
    `- Mode: ${h.mode}`,
    `- Model: ${h.model}`,
    `- Extraction prompt version: ${h.promptVersion}`,
    `- Comparison rules version: ${h.compareRulesVersion}`,
    `- Config thresholds: premium medium ${h.thresholds.premiumMediumPct} percent, premium high ${h.thresholds.premiumHighPct} percent, window ${h.thresholds.windowMinDays}-${h.thresholds.windowMaxDays} days (inclusive)`,
    `- Repeats: ${h.repeats}`,
    `- Documents: ${h.documents}`,
    `- Generated by: ${h.generatedBy}`,
    '',
    SYNTHETIC_LINE,
    '',
    `Caveat: ${AUTHOR_CAVEAT}`,
  ];
}

function failureTable(rows: readonly FailureRow[]): string[] {
  if (rows.length === 0) return ['No failures.'];
  return table(
    ['Version', 'Repeat', 'Policy', 'Side', 'Field', 'Expected', 'Actual', 'Explanation'],
    rows.map((f) => [f.promptVersion, String(f.repeat), f.policyId, f.side, f.field, f.expected, f.actual, f.explanation]),
  );
}

export function renderPlumbing(h: ReportHeader, p: PlumbingSummary): string {
  const lines = [
    '# Evaluation report - FAKE mode',
    '',
    '**PLUMBING CHECK - accuracy not measured.** The "model" in this mode returns the answer keys, so this run checks selection, comparison, outputs and pipeline outcomes only. It says nothing about how well a real model reads documents.',
    '',
    ...headerLines(h),
    '',
    '## Plumbing checks',
    '',
    ...table(['Check', 'Result'], [
      ['Selection correct (15 scenarios)', r(p.selectionCorrect)],
      ['Final status correct (D-D)', r(p.statusCorrect)],
      ['Packs built where expected', r(p.packs)],
      ['Compare engine diffs vs answer key (precision)', r(p.diffPrecision)],
      ['Compare engine diffs vs answer key (recall)', r(p.diffRecall)],
      ['Overall risk correct', r(p.riskCorrect)],
      ['Flags exact', r(p.flagsExact)],
      ['Pack files present (xlsx, 2 eml, summary)', r(p.filesOk)],
    ]),
    '',
    '## Pipeline outcome counts',
    '',
    ...table(['Outcome', 'Count'], Object.entries(p.pipelineCounts).map(([k, v]) => [k, String(v)])),
    '',
    '## Per scenario',
    '',
    ...table(
      ['Policy', 'Scenario', 'Selection', 'Status (expected)', 'Status (actual)', 'Risk (expected)', 'Risk (actual)', 'Flags exact'],
      p.scenarios.map((s) => [s.policyId, s.scenarioId, `${s.actualSelection}${s.selectionCorrect ? '' : ' (WRONG)'}`, s.expectedStatus, s.actualStatus, String(s.expectedRisk), String(s.actualRisk), s.flagsExact === null ? '-' : s.flagsExact ? 'yes' : 'NO']),
    ),
    '',
    '## Failures',
    '',
    ...failureTable(p.failures),
    '',
  ];
  return lines.join('\n');
}

function headlineRows(heads: readonly Headline[]): string[] {
  const label = (h: Headline) => (h.repeat === 'pooled' ? 'all repeats' : `repeat ${h.repeat}`);
  return table(
    ['Metric', ...heads.map(label)],
    [
      ['Documents measured (failed)', ...heads.map((h) => `${h.documents} (${h.documentsFailed})`)],
      ['Field values exact (8 fields)', ...heads.map((h) => r(h.fieldValue))],
      ['Source page correct', ...heads.map((h) => r(h.fieldPage))],
      ['Quote verification pass', ...heads.map((h) => r(h.quotePass))],
      ['Facts low confidence or null', ...heads.map((h) => String(h.lowOrNull))],
      ['Facts the model marked medium confidence', ...heads.map((h) => String(h.mediumConfidence))],
      ['WRONG value at high confidence', ...heads.map((h) => String(h.wrongHigh))],
      ['Exclusion keys precision', ...heads.map((h) => r(h.exclusionPrecision))],
      ['Exclusion keys recall', ...heads.map((h) => r(h.exclusionRecall))],
      ['Exclusion page correct (matched keys)', ...heads.map((h) => r(h.exclusionPage))],
      ['Differences precision (end to end)', ...heads.map((h) => r(h.diffPrecision))],
      ['Differences recall (end to end)', ...heads.map((h) => r(h.diffRecall))],
      ['Overall risk correct (11 packs)', ...heads.map((h) => r(h.riskCorrect))],
      ['Flags exact (11 packs)', ...heads.map((h) => r(h.flagsExact))],
      ['Selection correct (15)', ...heads.map((h) => r(h.selectionCorrect))],
      ['Final status correct (15)', ...heads.map((h) => r(h.statusCorrect))],
      ['Typed-error checks (pol-s07, pol-s08)', ...heads.map((h) => r(h.typedErrorChecks))],
      ['HTTP responses', ...heads.map((h) => String(h.httpResponses))],
      ['Responses beyond the first per document', ...heads.map((h) => String(h.validationRetries))],
      ['Failed calls (rate limited / timeouts)', ...heads.map((h) => `${h.failedCalls} (${h.rateLimited} / ${h.timeouts})`)],
      ['Backoff retries', ...heads.map((h) => String(h.transportRetries))],
      ['Input tokens (of which cached)', ...heads.map((h) => `${h.inputTokens} (${h.cachedInputTokens === null ? 'not reported' : h.cachedInputTokens})`)],
      ['Output tokens', ...heads.map((h) => String(h.outputTokens))],
      ['Summed document time (ms)', ...heads.map((h) => String(h.documentMs))],
      ['Cost (USD, see formula)', ...heads.map((h) => h.cost.toFixed(6))],
    ],
  );
}

function versionDetail(v: VersionSummary, pricing: Pricing): string[] {
  const repeats = v.repeats.map((h) => h.repeat);
  const lines = [
    `### Headline (${v.promptVersion}): every repeat side by side`,
    '',
    ...headlineRows([...v.repeats, v.pooled]),
    '',
    `Spread across repeats (mean / min / max): ${Object.entries(v.spread)
      .map(([k, s]) => `${k} ${pct(s.mean)} / ${pct(s.min)} / ${pct(s.max)}`)
      .join('; ')}.`,
    '',
    `### Per field (${v.promptVersion})`,
    '',
    ...table(
      ['Field', ...repeats.map((n) => `value r${n}`), 'value all', ...repeats.map((n) => `page r${n}`), 'page all', 'quote pass all', 'docs varying value', 'docs varying page', 'docs varying confidence'],
      v.fields.map((f) => [f.field, ...f.valuePerRepeat.map(r), r(f.valuePooled), ...f.pagePerRepeat.map(r), r(f.pagePooled), r(f.quotePassPooled), String(f.valueVariedDocs), String(f.pageVariedDocs), String(f.confidenceVariedDocs)]),
    ),
    '',
    `### Exclusions by document (${v.promptVersion})`,
    '',
    'pol-s04 (reworded gradual_deterioration in the renewal) and pol-s15 (vacant_or_unoccupied_building removed in the renewal) are called out in the Note column.',
    '',
    ...table(
      ['Policy', 'Side', 'Expected keys', ...repeats.map((n) => `r${n} precision / recall / page`), 'Note'],
      v.exclusionsByDocument.map((d) => [
        d.policyId,
        d.side,
        d.expectedKeys.join(', '),
        ...d.perRepeat.map((p) => `${r(p.precision)} / ${r(p.recall)} / ${r(p.page)}${p.missed.length ? ` missed ${p.missed.join('+')}` : ''}${p.extra.length ? ` extra ${p.extra.join('+')}` : ''}`),
        d.policyId === 'pol-s04' ? 'reworded exclusion: key must stay gradual_deterioration' : d.policyId === 'pol-s15' ? 'removed exclusion: renewal must NOT list vacant_or_unoccupied_building' : '',
      ]),
    ),
    '',
    `### Differences by severity, end to end (${v.promptVersion}, all repeats)`,
    '',
    ...table(['Severity', 'Expected', 'Matched', 'Missed', 'False'], Object.entries(v.diffsBySeverity).map(([s, c]) => [s, String(c.expected), String(c.matched), String(c.missed), String(c.falseDiffs)])),
    '',
    `### Final status per scenario (${v.promptVersion}; pol-s07, pol-s08, pol-s09 and pol-s12 highlighted)`,
    '',
    ...table(
      ['Policy', 'Scenario', 'Expected', ...repeats.map((n) => `r${n} status / risk / flags exact / missed / false`)],
      v.scenarios.map((s) => [
        ['pol-s07', 'pol-s08', 'pol-s09', 'pol-s12'].includes(s.policyId) ? `**${s.policyId}**` : s.policyId,
        s.scenarioId,
        s.expectedStatus,
        ...s.perRepeat.map((p) => `${p.status}${p.statusCorrect ? '' : ' (WRONG)'} / ${p.risk}${p.riskCorrect === false ? ' (WRONG)' : ''} / ${p.flagsExact === null ? '-' : p.flagsExact ? 'yes' : 'NO'} / ${p.missed} / ${p.falseDiffs}`),
      ]),
    ),
    '',
    `### Pipeline outcome counts per repeat (${v.promptVersion})`,
    '',
    ...table(['Outcome', ...repeats.map((n) => `r${n}`)], Object.keys(v.pipelineCounts[0] ?? {}).map((k) => [k, ...v.pipelineCounts.map((c) => String(c[k as keyof typeof c]))])),
    '',
    `### Time, tokens and cost (${v.promptVersion})`,
    '',
    ...table(['Measure', 'Value'], [
      ['Mean time per document (ms)', v.timing.meanDocumentMs.toFixed(0)],
      ['Min / max time per document (ms)', `${v.timing.minDocumentMs} / ${v.timing.maxDocumentMs}`],
      ['Mean input / output tokens per document', `${v.timing.meanInputTokensPerDocument.toFixed(1)} / ${v.timing.meanOutputTokensPerDocument.toFixed(1)}`],
      ['Policies with both documents measured (per repeat)', String(v.timing.policiesWithTwoDocuments)],
      ['Mean time per policy, both documents (ms)', v.timing.meanMsPerPolicy.toFixed(0)],
      ['Mean input / output tokens per policy', `${v.timing.meanInputTokensPerPolicy.toFixed(1)} / ${v.timing.meanOutputTokensPerPolicy.toFixed(1)}`],
      ['Mean cost per policy (USD)', v.timing.meanCostPerPolicy.toFixed(6)],
      ['Total cost, all repeats (USD)', v.pooled.cost.toFixed(6)],
    ]),
    '',
    `Cost formula: ${COST_FORMULA}. Prices: input ${pricing.inputPerMillion}, cached input ${pricing.cachedInputPerMillion}, output ${pricing.outputPerMillion} per million tokens, ${pricing.currency}. ${pricing.source} Times are wall-clock per document read (including any retries) on the author's machine and network.`,
    '',
    `### Prompt injection, live (${v.promptVersion}): pol-s14 must equal its answer key exactly`,
    '',
    ...table(
      ['Repeat', 'Facts exact (value and page, 2 documents)', 'Exclusions exact', 'Diffs exact', 'Flags exact', 'Status correct', 'Result'],
      v.injection.map((c) => [String(c.repeat), r(c.fieldsExact), c.exclusionsExact ? 'yes' : 'NO', c.diffsExact ? 'yes' : 'NO', c.flagsExact ? 'yes' : 'NO', c.statusCorrect ? 'yes' : 'NO', c.pass ? 'PASS' : 'FAIL']),
    ),
    '',
    `### Dangerous cases: wrong value still at high confidence (${v.promptVersion})`,
    '',
    ...(v.dangerous.length === 0
      ? ['None measured.']
      : table(['Repeat', 'Policy', 'Side', 'Field', 'Expected', 'Actual', 'Page'], v.dangerous.map((d) => [String(d.repeat), d.policyId, d.side, d.field, d.expected, d.actual, d.page]))),
    '',
    `### Every failure (${v.promptVersion}; values only, never document text)`,
    '',
    ...failureTable(v.failures),
    '',
  ];
  return lines;
}

export function renderLive(h: ReportHeader, versions: readonly VersionSummary[], finalVersion: string, finalReason: string, pricing: Pricing): string {
  const final = versions.find((v) => v.promptVersion === finalVersion) as VersionSummary;
  const earlier = versions.filter((v) => v !== final);
  return [
    '# Evaluation report - LIVE mode',
    '',
    ...headerLines(h),
    '',
    '## How this was measured',
    '',
    '- Extraction: every readable document that has answer-key terms was read through the real `readPolicyTerms` code path with the real model and the extraction cache disabled (no reads, no writes), once per repeat.',
    '- Replay: selection, comparison, outputs and final status were then produced by the real pipeline in a throwaway folder, with a reader that replays that repeat\'s measured extractions (the model is never called twice for the same document in a repeat).',
    '- Matching: numbers after removing commas and symbols, dates as yyyy-mm-dd, text trimmed, case-folded and whitespace-collapsed. A difference matches only when field (including the exclusion key), change and severity all match. Flags match on field and severity.',
    '- pol-s07 (renewal missing) and pol-s08 (image-only expiring) are checked separately for their typed errors, which must happen before any model call.',
    '- Percentages are shown with counts and truncated (never rounded up). Small samples are small samples: 28 documents is not a statistical study.',
    '',
    '## What this report does NOT prove',
    '',
    '- It does not show how the system reads REAL policy documents. The 28 documents share one template family written by the same author who wrote the answer keys; real documents vary far more.',
    '- A perfect score here does not mean the model cannot make mistakes. The sample is small, the layouts are clean, and every value is printed once on a predictable page.',
    '- It does not measure scanned documents, other languages, other policy types, long or multi-schedule documents, or endorsements.',
    "- The model's own confidence labels changed between repeats while its values did not; confidence is not a reliable signal on its own (only the plain-code quote check lowers confidence to 'low', which is what raises a human-check flag).",
    '- One prompt-injection document (pol-s14) with one phrasing is not proof of resistance to prompt injection in general.',
    '- Cost and time are for this model, this price and one machine and network on one day.',
    '',
    '## Prompt versions, side by side',
    '',
    ...table(
      ['Version', 'Repeats', 'Field values (all repeats)', 'Pages', 'Exclusion recall', 'Diff precision', 'Diff recall', 'Status correct', 'Wrong at high confidence'],
      versions.map((v) => [v.promptVersion, String(v.repeats.length), r(v.pooled.fieldValue), r(v.pooled.fieldPage), r(v.pooled.exclusionRecall), r(v.pooled.diffPrecision), r(v.pooled.diffRecall), r(v.pooled.statusCorrect), String(v.pooled.wrongHigh)]),
    ),
    '',
    `Final version: **${finalVersion}**. ${finalReason}`,
    '',
    `## Final version (${finalVersion})`,
    '',
    ...versionDetail(final, pricing),
    ...earlier.flatMap((v) => [`## Earlier version ${v.promptVersion} (kept in full; never hidden)`, '', ...versionDetail(v, pricing)]),
  ].join('\n');
}
